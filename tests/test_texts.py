"""UI strings, mail templates, generated server files and the client profile."""

import glob
import os
import re
import tempfile
import unittest

from dbovpn import mailer, pki, provision
from dbovpn.web import i18n
from tests import helpers

PKG = os.path.join(helpers.ROOT, "dbovpn")


class I18nTest(unittest.TestCase):
    def test_same_keys_in_both_languages(self):
        self.assertEqual(set(i18n.strings("en")), set(i18n.strings("tr")))

    def test_every_used_key_exists(self):
        used = set()
        for path in glob.glob(os.path.join(PKG, "web", "templates", "*.html")) + [os.path.join(PKG, "web", "app.py")]:
            with open(path, encoding="utf-8") as fh:
                text = fh.read()
            used |= set(re.findall(r"""\bt\(['"]([a-z0-9_]+)['"]""", text))
        for path in glob.glob(os.path.join(PKG, "*.py")):
            with open(path, encoding="utf-8") as fh:
                used |= set(re.findall(r'ServiceError\("([a-z0-9_]+)"', fh.read()))
        for path in [os.path.join(PKG, "passwords.py")]:
            with open(path, encoding="utf-8") as fh:
                used |= set(re.findall(r'return "(pw_[a-z_]+)"', fh.read()))
        used |= {"status_" + s for s in ("active", "pending", "disabled", "expired")} | {"lang_tr", "lang_en"}
        missing = sorted(k for k in used if not k.endswith("_") and k not in i18n.strings("en"))
        self.assertEqual(missing, [])

    def test_placeholders_match(self):
        en, tr = i18n.strings("en"), i18n.strings("tr")
        for key in en:
            self.assertEqual(set(re.findall(r"{(\w+)}", en[key])), set(re.findall(r"{(\w+)}", tr[key])), key)

    def test_turkish_file_uses_turkish_letters(self):
        text = " ".join(i18n.strings("tr").values())
        for ch in "çğıöşü":
            self.assertIn(ch, text)


class MailTemplateTest(unittest.TestCase):
    VALUES = {"customer": "Example Corp", "display_name": "Ali Veli", "username": "ali", "link": "https://x/enroll/t",
              "hours": 72, "panel_url": "https://x", "expires_on": "2026-10-24", "days_left": 7}

    def test_all_render(self):
        for lang in ("tr", "en"):
            for name in ("vpn_setup", "admin_setup", "expiry_7d", "expiry_0d"):
                subject, body = mailer.render(lang, name, self.VALUES)
                self.assertTrue(subject and body, (lang, name))
                self.assertNotIn("$", subject + body, (lang, name))


class ServerFilesTest(unittest.TestCase):
    def test_openvpn_config(self):
        cfg = helpers.example_config()
        text = provision.render("openvpn-server.conf", provision.openvpn_values(cfg))
        self.assertTrue(text.startswith("# Generated by dbo-vpn-gateway"))
        for line in ("port 1194", "proto udp", "server 10.8.0.0 255.255.255.0 nopool",
                     "tls-crypt /etc/openvpn/server/tc.key", "crl-verify /etc/openvpn/server/crl.pem",
                     "management /run/openvpn-server/example-vpn-mgmt.sock unix", "management-client-group dbovpn",
                     "management-client-auth", "auth-gen-token 43200 3600 external-auth", "user openvpn",
                     "explicit-exit-notify 1", "cert /etc/openvpn/server/pki/issued/example-vpn.crt"):
            self.assertIn("\n" + line + "\n", text, line)
        self.assertNotIn("push \"route", text)   # routes are per user, from the profile
        tcp = helpers.example_config(proto="tcp")
        self.assertNotIn("explicit-exit-notify", provision.render("openvpn-server.conf", provision.openvpn_values(tcp)))

    def test_nginx_site(self):
        cfg = helpers.example_config()
        text = provision.render("nginx-site.conf", provision.nginx_values(cfg))
        self.assertTrue(text.startswith("# Generated by dbo-vpn-gateway"))
        self.assertIn("limit_req_zone $binary_remote_addr zone=dbovpn_enroll", text)
        self.assertIn("allow 198.51.100.0/24;", text)
        self.assertIn("allow 203.0.113.7/32;", text)
        self.assertIn("deny all;", text)
        self.assertIn("proxy_pass http://127.0.0.1:8471;", text)
        self.assertIn("default-src 'self'", text)
        self.assertNotIn("$https_port", text)
        self.assertLess(text.index("location /enroll/"), text.index("deny all;"))

    def test_static_files_have_header(self):
        for name in ("sysctl.conf", "audit.rules", "dnf-automatic.conf"):
            self.assertIn("Generated by dbo-vpn-gateway", provision.render(name, {}).splitlines()[0], name)

    def test_shipped_files_have_header(self):
        files = glob.glob(os.path.join(helpers.ROOT, "systemd", "*")) + [
            os.path.join(helpers.ROOT, "conf", "sudoers"), os.path.join(helpers.ROOT, "conf", "gateway.conf.example")]
        for path in files:
            with open(path, encoding="utf-8") as fh:
                self.assertIn("dbo-vpn-gateway", fh.readline(), path)


class OvpnTest(unittest.TestCase):
    def test_profile(self):
        tmp = tempfile.mkdtemp()
        for d in ("issued", "private"):
            os.makedirs(os.path.join(tmp, "pki", d))
        files = {"pki/ca.crt": "-----BEGIN CERTIFICATE-----\nCA\n-----END CERTIFICATE-----\n",
                 "pki/issued/ali.crt": "Certificate:\n    Data: text dump\n-----BEGIN CERTIFICATE-----\nALI\n-----END CERTIFICATE-----\n",
                 "pki/private/ali.key": "-----BEGIN PRIVATE KEY-----\nKEY\n-----END PRIVATE KEY-----\n",
                 "tc.key": "-----BEGIN OpenVPN Static key V1-----\nTC\n-----END OpenVPN Static key V1-----\n"}
        for name, content in files.items():
            with open(os.path.join(tmp, name), "w") as fh:
                fh.write(content)
        cfg = helpers.example_config(pki_dir=os.path.join(tmp, "pki"), tls_crypt_key=os.path.join(tmp, "tc.key"))
        from tests.test_fixes import FakeOpenssl
        rsa = pki.EasyRSA(cfg, run=FakeOpenssl())
        text = pki.build_ovpn(cfg, "ali", rsa)
        lines = text.splitlines()
        for line in ("client", "proto udp", "remote vpn.example.com 1194", "auth-user-pass", "auth-nocache",
                     'static-challenge "Authenticator code" 1', "remote-cert-tls server", "<tls-crypt>"):
            self.assertIn(line, lines)
        self.assertNotIn("text dump", text)
        self.assertIn("<cert>\n-----BEGIN CERTIFICATE-----\nALI", text)
        with self.assertRaises(pki.PKIError):
            pki.build_ovpn(cfg, "nobody", rsa)

    def test_index_parsing(self):
        tmp = tempfile.mkdtemp()
        with open(os.path.join(tmp, "index.txt"), "w") as fh:
            fh.write("V\t281231000000Z\t\t01\tunknown\t/CN=example-vpn\n"
                     "V\t281231000000Z\t\t02\tunknown\t/CN=ali.veli\n"
                     "R\t281231000000Z\t261001000000Z\t03\tunknown\t/CN=old.user\n"
                     "V\t281231000000Z\t\t04\tunknown\t/CN=Bad Name\n")
        cfg = helpers.example_config(pki_dir=tmp)
        self.assertEqual(pki.EasyRSA(cfg).valid_client_names(), ["ali.veli", "Bad Name"])


